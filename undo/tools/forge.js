#!/usr/bin/env node
// FORGE — auto-tune level templates into verified, fair levels.
//
//   node tools/forge.js levels/factory.src.js [levelNumbers...]
//
// A source file exports { world, levels: [{ name, story, par, grid, make(p, H) }] }.
// `grid` lists candidate values for each tunable number; `make` builds the level from them
// using the sim helpers H (seg, body, bowl, block, ramp, dock, portals, ...).
// Forge tries every combination and keeps the one that:
//   1. goes wrong when you change nothing,
//   2. needs exactly `par` changes (not fewer),
//   3. has the most winning placements (most forgiving),
// then picks a natural hint, double-checks it with the full simulator,
// and writes levels/<world>.js for the game to load.
const fs = require('fs'), path = require('path');
const S = require('../sim.js'), T = require('./search.js'), H = S.helpers;

function combos(grid) {
  const keys = Object.keys(grid || {}); let out = [{}];
  for (const k of keys) out = out.flatMap((c) => grid[k].map((v) => Object.assign({}, c, { [k]: v })));
  return out;
}
function realise(spec, p, world) {
  const def = spec.make(p, H);
  return Object.assign(H.L(def), { name: spec.name, story: spec.story, par: spec.par, world, gravity: spec.gravity || def.gravity });
}
(async () => {
  const src = path.resolve(process.argv[2]); const only = process.argv.slice(3).map(Number);
  const mod = require(src), out = path.join(path.dirname(src), mod.world + '.js');
  let prev = {}; try { require(out).forEach((l) => { prev[l.name] = l; }); } catch (e) { /* first run */ }
  const results = [];
  for (const [i, spec] of mod.levels.entries()) {
    if (only.length && !only.includes(i + 1)) { results.push(prev[spec.name]); continue; }
    const t0 = Date.now(), cs = combos(spec.grid);
    let best = null;
    for (const p of cs) {
      const lv = realise(spec, p, mod.world);
      if (S.fastRun(lv, []).win) continue;                 // must go wrong by itself
      const a = await T.analyse(lv, 20);                   // coarse pass
      if (a.need !== spec.par) continue;
      const allToggle = a.sols.every((c) => c.every((e) => e.toggle));
      const score = allToggle ? 1000 : a.count;
      if (!best || score > best.score) best = { p, lv, score };
    }
    if (!best) { console.log(`✗ ${i + 1}. ${spec.name}: no settings work (${cs.length} tried)`); results.push(prev[spec.name]); continue; }
    const fine = await T.analyse(best.lv, 10);              // fine pass on the winner
    const hint = fine.hint, ok = hint && S.run(best.lv, hint).win && !S.run(best.lv, []).win;
    best.lv.hint = hint;
    results.push(best.lv);
    console.log(`${ok ? '✓' : '✗'} ${String(i + 1).padStart(2)}. ${spec.name.padEnd(18)} ${String(fine.count).padStart(4)} solutions · settings ${JSON.stringify(best.p)} · ${cs.length} tried in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
  }
  T.close();
  const body = JSON.stringify(results.filter(Boolean));
  fs.writeFileSync(out, `// GENERATED by tools/forge.js from ${path.basename(src)} — edit that file and re-run forge.\n(function () { var L = ${body};\n  if (typeof module !== 'undefined' && module.exports) module.exports = L; else UndoSim.addLevels(L); })();\n`);
  console.log('wrote', path.relative(process.cwd(), out));
})();
